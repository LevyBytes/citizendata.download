// Builds docs/scripts/hangar-link-ships.js, the ship table the Hangar Link and Fleetview export uses.
//
// Hangar Link identifies every ship by a short name of its own (a "slug", for example "mustang-omega"). A file it
// imports shows a ship in Fleetview only when the file names that ship by its slug. The slugs come from Hangar Link's
// public ship catalogue, https://hangar.link/ships.json. This script keeps only what the export needs from it:
// the slugs, and the item titles the catalogue lists for a slug. The catalogue's prices, images, and statistics are
// left out.
//
// Usage: download the catalogue, then run
//   node scripts/build-hangar-link-ships.mjs --from <path to ships.json>
//   node scripts/build-hangar-link-ships.mjs --from <path to ships.json> --check     (exit 1 when the table is stale)
//
// scripts/hangar-link-title-aliases.json holds spellings RSI has used for a ship that differ from its slug. Add a
// line there when a new ship is reported as "not in the ship table", then run this script again.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(repositoryRoot, "docs", "scripts", "hangar-link-ships.js");
const aliasPath = path.join(repositoryRoot, "scripts", "hangar-link-title-aliases.json");
const argumentsList = process.argv.slice(2);
const fromIndex = argumentsList.indexOf("--from");
const checkOnly = argumentsList.includes("--check");
if (fromIndex < 0 || !argumentsList[fromIndex + 1]) {
  console.error("Usage: node scripts/build-hangar-link-ships.mjs --from <path to ships.json> [--check]");
  process.exit(2);
}

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;
const byText = (left, right) => left < right ? -1 : left > right ? 1 : 0;

function fail(message) {
  console.error(`FAIL ${message}`);
  process.exit(1);
}

const catalogue = JSON.parse(await readFile(path.resolve(argumentsList[fromIndex + 1]), "utf8"));
if (!Array.isArray(catalogue?.ships) || catalogue.ships.length === 0) fail("The catalogue has no ships array.");

const slugs = [];
const titles = new Map();
for (const [index, ship] of catalogue.ships.entries()) {
  if (typeof ship?.slug !== "string" || !SLUG.test(ship.slug)) fail(`Catalogue ship ${index} has no usable slug.`);
  if (slugs.includes(ship.slug)) fail(`Catalogue slug ${ship.slug} is listed twice.`);
  slugs.push(ship.slug);
  for (const title of Array.isArray(ship.pledgeItemTitle) ? ship.pledgeItemTitle : []) {
    if (typeof title !== "string" || !title.trim()) fail(`Catalogue ship ${ship.slug} lists an empty item title.`);
    const key = title.trim().toLowerCase();
    if (titles.has(key) && titles.get(key) !== ship.slug) fail(`Item title "${title}" is listed for two ships.`);
    titles.set(key, ship.slug);
  }
}
slugs.sort(byText);

const aliasSource = JSON.parse(await readFile(aliasPath, "utf8"));
const aliases = new Map();
for (const [spelling, slug] of Object.entries(aliasSource.aliases ?? {})) {
  if (!/^[a-z0-9-]+$/u.test(spelling)) fail(`Alias "${spelling}" must be lower case letters, digits, and hyphens.`);
  if (!slugs.includes(slug)) fail(`Alias "${spelling}" names ${slug}, which is not in the catalogue.`);
  // A spelling that is itself a slug is found before the aliases are consulted, so an alias for it would never apply.
  if (slugs.includes(spelling)) fail(`Alias "${spelling}" is itself a catalogue slug.`);
  aliases.set(spelling, slug);
}

const table = {
  catalogue: String(catalogue.name ?? ""),
  catalogueCreatedAt: String(catalogue.createdAt ?? ""),
  slugs,
  titles: Object.fromEntries([...titles].sort(([left], [right]) => byText(left, right))),
  aliases: Object.fromEntries([...aliases].sort(([left], [right]) => byText(left, right)))
};
const json = JSON.stringify(table, null, 2).replaceAll("<", "\\u003c").replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");
const output = `// Ship names as Hangar Link spells them, for the Hangar Link and Fleetview export.
// Generated by scripts/build-hangar-link-ships.mjs from https://hangar.link/ships.json. Do not edit by hand.
globalThis.CitizenDataHangarLinkShips = ${json};
`;

let current = null;
try {
  current = await readFile(outputPath, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
if (current === output) {
  console.log(`PASS ship table is current: ${slugs.length} ships, ${titles.size} catalogue titles, ${aliases.size} aliases`);
} else if (checkOnly) {
  fail("docs/scripts/hangar-link-ships.js does not match the catalogue and alias file. Run this script without --check.");
} else {
  await writeFile(outputPath, output);
  console.log(`WROTE docs/scripts/hangar-link-ships.js: ${slugs.length} ships, ${titles.size} catalogue titles, ${aliases.size} aliases`);
}
